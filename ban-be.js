function buildExportNode(rel, wish) {
  const node = document.createElement("div");
  node.className = "postcard-export";

  const rows = [
    ["exp-date", "Ngày 20 tháng 10"],
    ["exp-greeting", `Gửi ${displayName()} ơi,`],
    ["exp-body", wish],
    ["exp-closing", rel.closing],
    ["exp-sign", rel.sign],
    ["exp-foot", "Chúc mừng Ngày Phụ nữ Việt Nam — 20 · 10"],
  ];

  rows.forEach(([className, text]) => {
    const p = document.createElement("p");
    p.className = className;
    p.textContent = text;
    node.appendChild(p);
  });

  return node;
}

async function downloadImage() {
  if (isExporting) return;

  if (typeof html2canvas === "undefined") {
    showToast("Không tải được thư viện ảnh. Thử lại khi có mạng.");
    return;
  }

  isExporting = true;
  imageWishBtn.classList.add("is-loading");
  imageWishBtn.textContent = "Đang tạo ảnh…";

  const rel = getRel(currentRel);
  const wish = wishText.textContent.trim();
  const exportNode = buildExportNode(rel, wish);
  exportNode.style.left = "0";
  exportNode.style.top = "0";
  exportNode.style.transform = "translateX(-120%)";
  document.body.appendChild(exportNode);

  const fileName = `Thu-ban-be-20-10-${displayName().replace(/\s+/g, "-")}.png`;

  try {
    if (document.fonts?.ready) {
      await document.fonts.ready;
    }

    const canvas = await html2canvas(exportNode, {
      scale: 2,
      useCORS: true,
      backgroundColor: "#fffaf5",
      logging: false,
    });

    const link = document.createElement("a");
    link.download = fileName;
    link.href = canvas.toDataURL("image/png");
    link.click();
    showToast("Đã tải ảnh thiệp thư");
  } catch {
    showToast("Không tạo được ảnh. Vui lòng thử lại.");
  } finally {
    exportNode.remove();
    isExporting = false;
    imageWishBtn.classList.remove("is-loading");
    imageWishBtn.textContent = "Tải ảnh";
  }
}

/* —— Hiệu ứng khi cuộn —— */
function observeReveals() {
  const items = document.querySelectorAll(".reveal");
  if (!items.length) return;

  if (!("IntersectionObserver" in window)) {
    items.forEach((item) => item.classList.add("is-visible"));
    return;
  }

  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          io.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -6% 0px" }
  );

  items.forEach((item) => io.observe(item));
}

function observeNotes() {
  const items = document.querySelectorAll(".note-list li");
  if (!items.length) return;

  if (notesObserver) notesObserver.disconnect();

  notesObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          notesObserver.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.35 }
  );

  items.forEach((item) => notesObserver.observe(item));
}

function updateHeader() {
  if (!siteHeader) return;
  siteHeader.classList.toggle("is-scrolled", window.scrollY > 24);
}

