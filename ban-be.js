const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

let currentRel = "hanh";
let currentIndex = 0;
let isAnimating = false;
let isExporting = false;
let toastTimer = null;
let notesObserver = null;

function getRel(id) {
  return RELATIONS[id] || RELATIONS.hanh;
}

function displayName() {
  const raw = (friendName.value || "").trim();
  return raw || "bạn thân";
}

function buildWish(index, rel) {
  return rel.wishes[index % rel.wishes.length];
}

function pickRandomIndex(exclude, total) {
  if (total <= 1) return 0;
  let next = exclude;
  while (next === exclude) {
    next = Math.floor(Math.random() * total);
  }
  return next;
}

function fillNotes(rel) {
  psNotes.innerHTML = rel.notes
    .map(
      (text) =>
        `<li><span class="note-mark" aria-hidden="true"><svg viewBox="0 0 32 32" fill="none"><path d="M16 28C6 20 2 15 2 10.5 2 6.4 5.2 3 9.2 3c2.3 0 4.4 1.1 5.8 2.9C16.4 4.1 18.5 3 20.8 3 24.8 3 28 6.4 28 10.5 28 15 24 20 16 28Z" fill="currentColor"/></svg></span><span>${text}</span></li>`
    )
    .join("");
  observeNotes();
}

function updateCopy(rel, { withNotes = false } = {}) {
  const name = displayName();
  friendGreeting.textContent = `Gửi ${name} ơi,`;
  friendClosing.textContent = rel.closing;
  friendSign.textContent = rel.sign;
  photoCaption.textContent = rel.caption;
  heroScript.textContent = `Gửi đến ${name}…`;
  heroLead.textContent = `Có những lời yêu thương cứ để trong lòng mãi — hôm nay, xin được viết ra thành một lá thư chỉ dành cho ${name}.`;
  if (withNotes) {
    psText.textContent = rel.ps;
    fillNotes(rel);
  }
}

function showWish(index, { animate = true } = {}) {
  const rel = getRel(currentRel);
  const text = buildWish(index, rel);
  currentIndex = index;
  wishCaption.textContent = `Dòng thư · ${index + 1}`;

  if (!animate) {
    wishText.textContent = text;
    return;
  }

  isAnimating = true;
  wishText.classList.remove("is-in");
  wishText.classList.add("is-out");

  window.setTimeout(() => {
    wishText.textContent = text;
    wishText.classList.remove("is-out");
    wishText.classList.add("is-in");
    isAnimating = false;
  }, 320);
}

function setRelation(id, { animateWish = true } = {}) {
  const rel = getRel(id);
  currentRel = id;
  relChips.querySelectorAll(".chip").forEach((chip) => {
    const active = chip.dataset.rel === id;
    chip.classList.toggle("is-active", active);
    chip.setAttribute("aria-checked", String(active));
  });

  updateCopy(rel, { withNotes: true });
  showWish(
    animateWish
      ? pickRandomIndex(currentIndex, rel.wishes.length)
      : Math.floor(Math.random() * rel.wishes.length),
    { animate: animateWish }
  );
}

function persist() {
  try {
    sessionStorage.setItem(STORAGE_KEY, JSON.stringify({ name: friendName.value, rel: currentRel }));
  } catch {
    /* ignore */
  }
}

function closeModal() {
  greetModal.classList.add("is-leaving");
  document.body.classList.remove("locked");

  window.setTimeout(() => {
    greetModal.hidden = true;
    greetModal.classList.remove("is-leaving");
    greetModal.setAttribute("aria-hidden", "true");
  }, 520);
}

function openModal() {
  greetModal.hidden = false;
  greetModal.classList.remove("is-leaving");
  greetModal.removeAttribute("aria-hidden");
  document.body.classList.add("locked");
  window.scrollTo(0, 0);
  window.setTimeout(() => friendName.focus(), 60);
}

function startSending() {
  const rel = getRel(currentRel);
  updateCopy(rel, { withNotes: true });
  showWish(Math.floor(Math.random() * rel.wishes.length), { animate: false });
  persist();
  burstHearts();
  closeModal();
}

function showToast(message) {
  copyToast.textContent = message;
  copyToast.hidden = false;
  window.clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => {
    copyToast.hidden = true;
  }, 1800);
}

function buildFullLetter(rel, wish) {
  return [
    `Gửi ${displayName()} ơi,`,
    "",
    wish,
    "",
    rel.closing,
    rel.sign,
  ].join("\n");
}

/* —— Trái tim bắn ra —— */
function burstHearts() {
  if (reduceMotion || !heartField) return;

  const sticker = document.querySelector(".greet-sticker");
  const origin = sticker
    ? {
        x: sticker.getBoundingClientRect().left + sticker.offsetWidth / 2,
        y: sticker.getBoundingClientRect().top + sticker.offsetHeight / 2,
      }
    : { x: window.innerWidth / 2, y: window.innerHeight / 2 };

  const tints = ["#f0a6b3", "#ef9a76", "#e9aab6", "#c8607a"];

  for (let i = 0; i < 18; i++) {
    const heart = document.createElement("span");
    heart.className = "heart heart-burst";
    heart.style.left = `${origin.x}px`;
    heart.style.top = `${origin.y}px`;
    heart.style.setProperty("--size", `${10 + Math.random() * 12}px`);
    heart.style.setProperty("--tint", tints[i % tints.length]);
    heartField.appendChild(heart);

    const angle = Math.random() * Math.PI * 2;
    const distance = 90 + Math.random() * 210;
    const dx = Math.cos(angle) * distance;
    const dy = Math.sin(angle) * distance - 120;
    const spin = 180 + Math.random() * 480;

    const animation = heart.animate(
      [
        { transform: "translate3d(0, 0, 0) rotate(0deg) scale(0.6)", opacity: 0 },
        { opacity: 0.85, offset: 0.12 },
        { transform: `translate3d(${dx}px, ${dy}px, 0) rotate(${spin}deg) scale(1)`, opacity: 0 },
      ],
      { duration: 1400 + Math.random() * 900, easing: "cubic-bezier(0.2, 0.7, 0.3, 1)", fill: "forwards" }
    );

    animation.onfinish = () => heart.remove();
  }
}

/* —— Trái tim bay nền —— */
function createHearts() {
  if (reduceMotion) return;

  const count = window.innerWidth < 640 ? 7 : 12;
  const tints = ["#f0a6b3", "#ef9a76", "#e9aab6", "#c8607a", "#7fa695"];
  heartField.innerHTML = "";

  for (let i = 0; i < count; i++) {
    const heart = document.createElement("span");
    heart.className = "heart";
    heart.style.setProperty("--x", `${Math.random() * 100}%`);
    heart.style.setProperty("--size", `${10 + Math.random() * 16}px`);
    heart.style.setProperty("--dur", `${15 + Math.random() * 16}s`);
    heart.style.setProperty("--delay", `${-Math.random() * 20}s`);
    heart.style.setProperty("--drift", `${-50 + Math.random() * 100}px`);
    heart.style.setProperty("--tint", tints[i % tints.length]);
    heartField.appendChild(heart);
  }
}

